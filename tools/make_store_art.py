"""App icon, splash art and Play Store graphics from the game's own art
(T-030, D-035). No new art and no fonts: Mochi's victory frame on the
palette's sun yellow, and a storybook scene for the feature graphic.

    python3 -I tools/make_store_art.py
"""
import os

from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
RES = f'{ROOT}/app/android/app/src/main/res'
STORE = f'{ROOT}/docs/release'
SUN = (249, 214, 78, 255)      # Palette.sun
PAPER = (255, 251, 242, 255)   # Palette.paper
INK = (51, 41, 31, 255)        # Palette.ink
DENSITY = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}


def mochi_bust() -> Image.Image:
    """Victory Mochi from the head down to the belly, trimmed."""
    im = Image.open(f'{ROOT}/assets/raw/frames/mochi2/cat_mochi_victory.png').convert('RGBA')
    l, t, r, b = im.getbbox()
    return im.crop((l, t, r, t + int((b - t) * 0.78)))


def fit(im: Image.Image, box: int) -> Image.Image:
    s = box / max(im.size)
    return im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)


def foreground(size: int) -> Image.Image:
    """Adaptive-icon foreground: Mochi's bust standing on the bottom edge
    (the cut is hidden by the mask), head inside the 66/108 safe circle."""
    fg = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    art = mochi_bust()
    art = art.resize((round(size * 0.84), round(size * 0.84 * art.height / art.width)), Image.LANCZOS)
    fg.alpha_composite(art, ((size - art.width) // 2, size - art.height))
    return fg


def full_icon(size: int, radius: float) -> Image.Image:
    """Background + foreground, masked to a rounded square (legacy / store)."""
    big = size * 4
    canvas = Image.new('RGBA', (big, big), SUN)
    # soft paper glow behind Mochi
    glow = Image.new('RGBA', (big, big), (255, 240, 180, 0))  # no dark rim
    ImageDraw.Draw(glow).ellipse((big * 0.2, big * 0.12, big * 0.8, big * 0.72), fill=(255, 240, 180, 255))
    canvas.alpha_composite(glow.filter(ImageFilter.GaussianBlur(big * 0.05)))
    canvas.alpha_composite(foreground(big))
    mask = Image.new('L', (big, big), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, big - 1, big - 1), radius=int(big * radius), fill=255)
    canvas.putalpha(mask)
    return canvas.resize((size, size), Image.LANCZOS)


def save_small(im: Image.Image, path: str):
    """256 colours like the sprites (D-030): same look, a fraction of the size."""
    im.quantize(colors=256, method=Image.Quantize.FASTOCTREE).save(path, optimize=True)


def write_android():
    for d, k in DENSITY.items():
        os.makedirs(f'{RES}/mipmap-{d}', exist_ok=True)
        save_small(full_icon(round(48 * k), 0.22), f'{RES}/mipmap-{d}/ic_launcher.png')
        fg = foreground(round(108 * k))
        save_small(fg, f'{RES}/mipmap-{d}/ic_launcher_foreground.png')
        # themed (Android 13+) icon: Mochi's silhouette
        mono = Image.new('RGBA', fg.size, (0, 0, 0, 0))
        mono.putalpha(fg.getchannel('A'))
        mono.save(f'{RES}/mipmap-{d}/ic_launcher_monochrome.png', optimize=True)
        # splash art (pre-12 launch_background + 12+ splash icon): Mochi on paper
        os.makedirs(f'{RES}/drawable-{d}', exist_ok=True)
        save_small(fit(mochi_bust(), round(160 * k)), f'{RES}/drawable-{d}/splash_mochi.png')
    os.makedirs(f'{RES}/mipmap-anydpi-v26', exist_ok=True)
    with open(f'{RES}/mipmap-anydpi-v26/ic_launcher.xml', 'w') as f:
        f.write('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_store_art.py (T-030) -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
''')
    with open(f'{RES}/values/colors.xml', 'w') as f:
        f.write('''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_store_art.py (T-030): Palette.sun / Palette.paper -->
<resources>
    <color name="ic_launcher_background">#F9D64E</color>
    <color name="splash_background">#FFFBF2</color>
</resources>
''')


def write_store():
    os.makedirs(STORE, exist_ok=True)
    # Play listing icon: 512×512, Play applies its own mask (no rounding)
    full_icon(512, 0.0).convert('RGB').save(f'{STORE}/play_icon_512.png', optimize=True)
    # feature graphic 1024×500: the chapter 1 page, Mochi meeting a slime
    W, H = 1024, 500
    g = Image.new('RGBA', (W, H), PAPER)
    bg = f'{ROOT}/assets/raw/backgrounds'
    gy = int(H * 0.8)  # ground line; layers stacked as the game does
    hg = int((H - gy) / 0.3)
    for name, h, bottom in [('bg_book1_L0_sky', H, H),
                            ('bg_book1_ch1_L1_far', int(H * 0.62), gy + int(H * 0.04)),
                            ('bg_book1_ch1_L2_mid', int(H * 0.6), gy + int(H * 0.06)),
                            ('bg_book1_L3_ground', hg, gy + int(0.3 * hg))]:
        layer = Image.open(f'{bg}/{name}.png').convert('RGBA')
        layer = layer.resize((round(layer.width * h / layer.height), h), Image.LANCZOS)
        x = 0
        while x < W:
            g.alpha_composite(layer, (x, bottom - h))
            x += layer.width
    cat = fit(Image.open(f'{ROOT}/assets/raw/frames/mochi2/cat_mochi_victory.png').convert('RGBA'), 300)
    g.alpha_composite(cat, (300, gy + 10 - cat.height))
    slime = Image.open(f'{ROOT}/assets/raw/frames/eraserslime/mon_eraserslime_idle_f1.png').convert('RGBA')
    slime = fit(slime.crop(slime.getbbox()), 150)
    g.alpha_composite(slime, (640, gy + 4 - slime.height))
    acorn = Image.open(f'{ROOT}/assets/raw/frames/acorn/mon_acorn_idle_f1.png').convert('RGBA')
    acorn = fit(acorn.crop(acorn.getbbox()), 120)
    g.alpha_composite(acorn, (800, gy + 4 - acorn.height))
    g.convert('RGB').save(f'{STORE}/play_feature_1024x500.png', optimize=True)


if __name__ == '__main__':
    write_android()
    write_store()
    print('icons, splash art and store graphics written')
